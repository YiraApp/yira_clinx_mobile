import 'package:yiraclinics/features/domain/entities/provider_profile/provider_profile_entity.dart';

class ProviderProfileModel extends ProviderProfileEntity {
  const ProviderProfileModel({
    super.id,
    super.userId,
    super.name,
    super.firstName,
    super.lastName,
    super.email,
    super.phoneNumber,
    super.gender,
    super.dob,
    super.bloodGroup,
    super.imagePath,
    super.profileImageUrl,
    super.specialty,
    super.subSpecialty,
    super.department,
    super.registrationNumber,
    super.qualification,
    super.experience,
    super.consultationFee,
    super.bio,
    super.hospitalId,
    super.hospitalName,
    super.clinicAddress,
    super.orgId,
    super.orgName,
    super.isEmailVerified,
    super.isMobileVerified,
  });

  factory ProviderProfileModel.fromJson(Map<String, dynamic> json) {
    return ProviderProfileModel(
      id: json['id'] is int ? json['id'] : int.tryParse(json['id']?.toString() ?? ''),
      userId: json['userId']?.toString() ?? json['UserId']?.toString(),
      name: json['name']?.toString() ?? json['Name']?.toString(),
      firstName: json['firstName']?.toString() ?? json['FirstName']?.toString(),
      lastName: json['lastName']?.toString() ?? json['LastName']?.toString(),
      email: json['email']?.toString() ?? json['Email']?.toString(),
      phoneNumber: json['phoneNumber']?.toString() ?? json['PhoneNumber']?.toString(),
      gender: json['gender']?.toString() ?? json['Gender']?.toString(),
      dob: json['dob']?.toString() ?? json['DateOfBirth']?.toString(),
      bloodGroup: json['bloodGroup']?.toString() ?? json['BloodGroup']?.toString(),
      imagePath: json['imagePath']?.toString() ?? json['ImagePath']?.toString() ?? json['photoUrl']?.toString(),
      profileImageUrl: json['profileImageUrl']?.toString() ?? json['imagePath']?.toString() ?? json['ImagePath']?.toString() ?? json['photoUrl']?.toString(),
      specialty: json['specialty']?.toString() ?? json['Specialty']?.toString(),
      subSpecialty: json['subSpecialty']?.toString() ?? json['SubSpecialty']?.toString(),
      department: json['department']?.toString() ?? json['Department']?.toString(),
      registrationNumber: json['registrationNumber']?.toString() ?? json['RegistrationNumber']?.toString(),
      qualification: json['qualification']?.toString() ?? json['Qualification']?.toString(),
      experience: json['experience']?.toString() ?? json['Experience']?.toString(),
      consultationFee: json['consultationFee'] != null
          ? double.tryParse(json['consultationFee'].toString())
          : null,
      bio: json['bio']?.toString() ?? json['Bio']?.toString(),
      hospitalId: json['hospitalId'] is int ? json['hospitalId'] : int.tryParse(json['hospitalId']?.toString() ?? ''),
      hospitalName: json['hospitalName']?.toString() ?? json['HospitalName']?.toString(),
      clinicAddress: json['clinicAddress']?.toString() ?? json['ClinicAddress']?.toString(),
      orgId: json['orgId'] is int ? json['orgId'] : int.tryParse(json['orgId']?.toString() ?? ''),
      orgName: json['orgName']?.toString() ?? json['OrgName']?.toString(),
      isEmailVerified: json['isEmailVerified'] == true || json['IsEmailVerified'] == 1 || json['IsEmailVerified'] == true,
      isMobileVerified: json['isMobileVerified'] == true || json['IsMobileVerified'] == 1 || json['IsMobileVerified'] == true,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'userId': userId,
      'name': name,
      'firstName': firstName,
      'lastName': lastName,
      'email': email,
      'phoneNumber': phoneNumber,
      'gender': gender,
      'dob': dob,
      'bloodGroup': bloodGroup,
      'imagePath': imagePath,
      'profileImageUrl': profileImageUrl,
      'specialty': specialty,
      'subSpecialty': subSpecialty,
      'department': department,
      'registrationNumber': registrationNumber,
      'qualification': qualification,
      'experience': experience,
      'consultationFee': consultationFee,
      'bio': bio,
      'hospitalId': hospitalId,
      'hospitalName': hospitalName,
      'clinicAddress': clinicAddress,
      'orgId': orgId,
      'orgName': orgName,
      'isEmailVerified': isEmailVerified,
      'isMobileVerified': isMobileVerified,
    };
  }
}
